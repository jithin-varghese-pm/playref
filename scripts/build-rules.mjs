// Compiles rules/uno-classic.md and rules/uno-classic-fights.json into
// shared/generated/rules-data.ts so the browser, the server, the tests and
// the eval runner all read the same data. Fails loudly on bad input.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const md = readFileSync(join(root, 'rules/uno-classic.md'), 'utf8').replace(/\r\n/g, '\n');
const fightsRaw = readFileSync(join(root, 'rules/uno-classic-fights.json'), 'utf8').replace(/\r\n/g, '\n');

export function parseCards(text) {
  const cards = [];
  const blocks = text.split(/^## /m).slice(1);
  for (const block of blocks) {
    const [heading, ...lines] = block.split('\n');
    const m = /^(R\d+):\s*(.+)$/.exec(heading.trim());
    if (!m) throw new Error(`Bad rule card heading: "${heading}"`);
    const official = lines.find((l) => l.startsWith('Official:'));
    const house = lines.find((l) => l.startsWith('House:'));
    if (!official || !house) throw new Error(`Rule card ${m[1]} needs Official: and House: lines`);
    cards.push({
      id: m[1],
      title: m[2].trim(),
      official: official.slice('Official:'.length).trim(),
      house: house.slice('House:'.length).trim(),
    });
  }
  return cards;
}

const cards = parseCards(md);
const fights = JSON.parse(fightsRaw).fights;
const ids = new Set(cards.map((c) => c.id));
for (const f of fights) {
  for (const c of f.cards) if (!ids.has(c)) throw new Error(`Fight ${f.id} cites unknown card ${c}`);
}
const version = createHash('sha256').update(md).update(fightsRaw).digest('hex').slice(0, 12);
const rulesText = cards.map((c) => `${c.id}: ${c.title}\nOfficial: ${c.official}\nHouse: ${c.house}`).join('\n\n');

const out = `// GENERATED by scripts/build-rules.mjs. Do not edit. Edit rules/ instead.
import type { Fight, RuleCard } from '../types';

export const RULES_VERSION = ${JSON.stringify(version)};
export const RULE_CARDS: RuleCard[] = ${JSON.stringify(cards, null, 2)};
export const FIGHTS: Fight[] = ${JSON.stringify(fights, null, 2)} as Fight[];
/** Compact text of every rule card, sent to the AI with each new question. */
export const RULES_TEXT: string = ${JSON.stringify(rulesText)};
`;
mkdirSync(join(root, 'shared/generated'), { recursive: true });
writeFileSync(join(root, 'shared/generated/rules-data.ts'), out);
console.log(`rules: ${cards.length} cards, ${fights.length} fights, version ${version}`);
