// Compiles the rule cards and known fights in rules/ into shared/generated/*.ts
// so the browser, the server, the tests and the eval runner all read the same
// data. Fails loudly on bad input.
//   UNO:      rules/uno-classic.md + rules/uno-classic-fights.json -> rules-data.ts
//   Imposter: rules/imposter.md    + rules/imposter-fights.json    -> imposter-data.ts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n');

export function parseCards(text, prefix) {
  const cards = [];
  const blocks = text.split(/^## /m).slice(1);
  for (const block of blocks) {
    const [heading, ...lines] = block.split('\n');
    const m = new RegExp(`^(${prefix}\\d+):\\s*(.+)$`).exec(heading.trim());
    if (!m) throw new Error(`Bad rule card heading: "${heading}"`);
    const official = lines.find((l) => l.startsWith('Official:'));
    const house = lines.find((l) => l.startsWith('House:'));
    if (!official || !house) throw new Error(`Rule card ${m[1]} needs Official: and House: lines`);
    cards.push({ id: m[1], title: m[2].trim(), official: official.slice('Official:'.length).trim(), house: house.slice('House:'.length).trim() });
  }
  return cards;
}

function compile(mdPath, fightsPath, prefix) {
  const md = read(mdPath);
  const fightsRaw = read(fightsPath);
  const cards = parseCards(md, prefix);
  const fights = JSON.parse(fightsRaw).fights;
  const ids = new Set(cards.map((c) => c.id));
  for (const f of fights) for (const c of f.cards) if (!ids.has(c)) throw new Error(`Fight ${f.id} cites unknown card ${c}`);
  const version = createHash('sha256').update(md).update(fightsRaw).digest('hex').slice(0, 12);
  return { cards, fights, version };
}

mkdirSync(join(root, 'shared/generated'), { recursive: true });

// UNO (unchanged exports, so the AI pipeline and saved answers are not affected).
const uno = compile('rules/uno-classic.md', 'rules/uno-classic-fights.json', 'R');
const rulesText = uno.cards.map((c) => `${c.id}: ${c.title}\nOfficial: ${c.official}\nHouse: ${c.house}`).join('\n\n');
writeFileSync(
  join(root, 'shared/generated/rules-data.ts'),
  `// GENERATED by scripts/build-rules.mjs. Do not edit. Edit rules/ instead.
import type { Fight, RuleCard } from '../types';

export const RULES_VERSION = ${JSON.stringify(uno.version)};
export const RULE_CARDS: RuleCard[] = ${JSON.stringify(uno.cards, null, 2)};
export const FIGHTS: Fight[] = ${JSON.stringify(uno.fights, null, 2)} as Fight[];
/** Compact text of every rule card, sent to the AI with each new question. */
export const RULES_TEXT: string = ${JSON.stringify(rulesText)};
`,
);
console.log(`rules: UNO ${uno.cards.length} cards, ${uno.fights.length} fights, version ${uno.version}`);

// Imposter.
const imp = compile('rules/imposter.md', 'rules/imposter-fights.json', 'I');
writeFileSync(
  join(root, 'shared/generated/imposter-data.ts'),
  `// GENERATED by scripts/build-rules.mjs. Do not edit. Edit rules/ instead.
import type { Fight, RuleCard } from '../types';

export const IMPOSTER_RULES_VERSION = ${JSON.stringify(imp.version)};
export const IMPOSTER_CARDS: RuleCard[] = ${JSON.stringify(imp.cards, null, 2)};
export const IMPOSTER_FIGHTS: Fight[] = ${JSON.stringify(imp.fights, null, 2)} as Fight[];
`,
);
console.log(`rules: Imposter ${imp.cards.length} cards, ${imp.fights.length} fights, version ${imp.version}`);
